'use strict';
const fs=require('fs'), vm=require('vm'), assert=require('assert');
const html=fs.readFileSync(require('path').join(__dirname,'../public/index.html'),'utf8');
const fn=html.match(/function validateTripFormValues\([^]*?\n}\n(?=async function saveTripForm)/);
assert(fn,'missing trip validation function');
const context={TRIP_TYPES:['leisure','business','familyVisit','romantic','other','city','beach','winter','adventure'],LEGACY_TRIP_TYPES:new Set(['city','beach','winter','adventure'])};
vm.createContext(context);vm.runInContext(fn[0],context);
const v=x=>context.validateTripFormValues(x);
assert.strictEqual(v({selectedType:'business',start:'2026-11-02',end:'2026-11-06',budgetRaw:'150.50'}).ok,true);
assert.strictEqual(v({editing:true,existingType:'city',selectedType:'',budgetRaw:'0'}).tripType,'city','must preserve old type');
assert.strictEqual(v({editing:true,existingType:'city',selectedType:'business'}).tripType,'business');
assert.strictEqual(v({editing:false,selectedType:'city'}).ok,false,'must not create legacy type');
assert.strictEqual(v({editing:false,selectedType:''}).ok,false,'new trip requires purpose');
assert.strictEqual(v({editing:false,selectedType:'business',start:'2026-12-11',end:'2026-12-10'}).ok,false,'reject reversed dates');
for(const budgetRaw of ['-1','Infinity','1e309','invalid']) assert.strictEqual(v({selectedType:'leisure',budgetRaw}).ok,false,'invalid budget '+budgetRaw);
assert.strictEqual(v({selectedType:'leisure',budgetRaw:''}).budget,0);
assert.strictEqual(v({selectedType:'familyVisit',budgetRaw:'0',lang:'en'}).ok,true);
assert(!html.includes("LEGACY_TRIP_TYPES.has(tr.tripType)?tt2==='leisure'"),'silent legacy conversion persists');
assert(!/Categor[ií]as anteriores|previous categor(?:y|ies)/i.test(html),'old heading visible');
const ios=fs.readFileSync(require('path').join(__dirname,'../ios-capacitor/www/index.html'),'utf8');
assert.strictEqual(ios,html,'iOS source differs from web');
console.log('PASS V10.5.2 validation: original types preserved, purpose choices, date order, budgets, web/iOS parity');
