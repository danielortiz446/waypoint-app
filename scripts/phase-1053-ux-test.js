'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const html=fs.readFileSync(path.join(__dirname,'../public/index.html'),'utf8');
const source=html.match(/function viewTripDetail\(\)\{[\s\S]*?\n\}\nfunction setTripMoreBodyState\(/);
assert(source,'trip UI functions must be present');
const block=source[0];
for (const section of ['today','itinerary','ai','map']) assert(block.includes(`['${section}'`)||block.includes(`,'${section}'`),`Main navigation missing ${section}`);
for (const section of ['overview','bookings','budget','checklist','calendar','flights','travel','notes','assistance','polls','ideas','activity','recap']) assert(block.includes(`'${section}'`),`More menu omitted ${section}`);
assert(!block.includes('wp-extras-strip'),'Duplicate tools bar must be removed');
assert(!html.includes("if(tr.travelMode&&['overview','itinerary'"),'Travel Mode should not redirect away from itinerary');
assert(html.includes('oninput="filterHomeTrips(this.value)"'),'home typing must preserve focus');
assert(!html.includes('oninput="ui.tripSearch=this.value;render();"'),'home search rerender bug resurfaced');
assert(html.includes('function filterHomeTrips(query)'),'incremental home search missing');
assert(!/function tripCard\(tr\)\{[\s\S]*?document.body.classList.toggle\('travel-mode-active'/.test(html.split('function openTripActions(')[0].split('function tripCard(tr){')[1]||''),'home cards must not toggle global travel mode');
assert(html.includes("ui.screen==='trip'&&tripById(ui.currentTripId)?.travelMode"),'travel mode should reflect active trip');
const ios=fs.readFileSync(path.join(__dirname,'../ios-capacitor/www/index.html'),'utf8');
assert.equal(ios,html,'web/iOS HTML must match');
console.log('PASS simple navigation contains primary + all secondary tools');
console.log('PASS no duplicate toolbar or forced Travel Mode redirects');
console.log('PASS home live search preserves keyboard focus and no leaked travel-mode CSS');
console.log('PASS exact web/Capacitor HTML parity');
